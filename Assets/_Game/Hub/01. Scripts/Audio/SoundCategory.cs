    /// <summary>게임 안에서 나는 소리. 발소리, 조리 기구, 손님.</summary>
    SFX,

    /// <summary>버튼과 알림처럼 화면에서 나는 소리. 게임이 멈춰도 들려야 한다.</summary>
    UI,
}

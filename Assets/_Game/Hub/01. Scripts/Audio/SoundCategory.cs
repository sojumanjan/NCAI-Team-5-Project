/// <summary>
/// 소리의 갈래. 믹서 그룹과 볼륨 설정이 이 단위로 나뉜다.
///
/// 셋으로 고정한 이유는 옵션 화면에 슬라이더가 몇 개나 필요한가에서 나왔다. 더 잘게 쪼개면
/// 믹서 그룹과 노출 파라미터를 다시 만들어야 하므로, 늘릴 일이 생기면 팀장에게 말할 것.
/// </summary>
public enum SoundCategory
{
    /// <summary>배경음. 한 번에 하나만 흐르고 곡이 바뀔 때 크로스페이드한다.</summary>
